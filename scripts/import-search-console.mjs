import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, relative, isAbsolute } from 'node:path';
import { importSearchConsole, analyzeSearchConsole } from './lib/search-console.mjs';
import { keywordRegistry } from '../data/content-operations.ts';
import { guides } from '../src/data/guides.ts';
import { liveTools } from '../src/data/liveTools.ts';
import { canonicalIndexableUrls } from '../src/lib/indexnow.ts';
const input = process.argv[2];
if (!input) throw new Error('Usage: node scripts/import-search-console.mjs input.csv [minimumImpressions=100] [maximumClicks=5]');
const root = resolve('data/search-console/private');
const target = resolve(root, 'normalized.json');
const rel = relative(root, target);
if (rel.startsWith('..') || isAbsolute(rel)) throw new Error('Output must remain project-local');
const minimumImpressions = Number(process.argv[3] ?? 100), maximumClicks = Number(process.argv[4] ?? 5);
if (![minimumImpressions, maximumClicks].every(v => Number.isFinite(v) && v >= 0)) throw new Error('Thresholds must be nonnegative numbers');
const rows = importSearchConsole(await readFile(input, 'utf8'));
const analysis = analyzeSearchConsole(rows, { minimumImpressions, maximumClicks, canonicalUrls: canonicalIndexableUrls(), knownQueries: [...keywordRegistry.map(k => k.query), ...guides.flatMap(g => [g.primaryQuery, ...g.secondaryQueries]), ...liveTools.map(t => t.name)] });
await mkdir(root, { recursive: true });
await writeFile(target, JSON.stringify({ rows, analysis }, null, 2));
console.log(`Imported ${rows.length} rows into ignored project-local JSON. Missing metrics remain null.`);
