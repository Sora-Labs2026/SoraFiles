import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { liveTools } from '../src/data/liveTools.ts';
import { POPULARITY_BOOTSTRAP_CANDIDATES, POPULARITY_LIMIT } from '../src/lib/popularity/config.js';

const target = fileURLToPath(new URL('../src/data/popularityRegistry.generated.js', import.meta.url));
const published = [...new Set(liveTools.map(({ id }) => id))];
const publishedSet = new Set(published);
const bootstrap = [...new Set([...POPULARITY_BOOTSTRAP_CANDIDATES, ...published])]
  .filter((id) => publishedSet.has(id))
  .slice(0, POPULARITY_LIMIT);
const output = `// Generated from src/data/liveTools.ts by scripts/generate-popularity-registry.mjs.\n// Do not edit this file by hand.\nexport const PUBLISHED_TOOL_IDS = ${JSON.stringify(published)};\nexport const BOOTSTRAP_POPULAR_TOOL_IDS = ${JSON.stringify(bootstrap)};\n`;

let current = '';
try { current = await readFile(target, 'utf8'); } catch {}
if (current !== output) await writeFile(target, output, 'utf8');
console.log(`Popularity registry ready: ${published.length} published tools, ${bootstrap.length} bootstrap positions.`);
